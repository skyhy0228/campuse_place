export const DICTS: Record<Lang, Dict> = { ko, zh };

export function readLang(): Lang {
  try {
    return localStorage.getItem(KEY) === "zh" ? "zh" : "ko";
  } catch {
    return "ko";
  }
}

export function applyLang(lang: Lang) {
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "ko";
}

interface LangValue {
  lang: Lang;
  t: Dict;
  setLang: (lang: Lang) => void;
}

const LangContext = createContext<LangValue | null>(null);

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang);
  useEffect(() => applyLang(lang), [lang]);
  const setLang = useCallback((next: Lang) => {
    try {
      localStorage.setItem(KEY, next);
    } catch {
      // 저장하지 못해도 이번 화면에는 적용한다.
    }
    setLangState(next);
  }, []);
  const value = useMemo(() => ({ lang, t: DICTS[lang], setLang }), [lang, setLang]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  const value = useContext(LangContext);
  if (!value) throw new Error("LangProvider 안에서만 사용할 수 있습니다.");
  return value;
}
